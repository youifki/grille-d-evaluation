/* بحث في قاعدة البيانات */
function searchCommunes(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const results = [];
  COMMUNES_DB.forEach(region => {
    region.provinces.forEach(province => {
      province.communes.forEach(c => {
        if (c.n.includes(q)) {
          results.push({ commune: c.n, type: c.t === 'ح' ? 'حضرية' : 'قروية', province: province.name, region: region.name });
        }
      });
    });
  });
  return results;
}

/* الحصول على كل الجماعات كقائمة مسطحة */
function getAllCommunes() {
  const list = [];
  COMMUNES_DB.forEach(region => {
    region.provinces.forEach(province => {
      province.communes.forEach(c => {
        list.push({ name: c.n, type: c.t === 'ح' ? 'حضرية' : 'قروية', province: province.name, region: region.name, regionId: region.id });
      });
    });
  });
  return list;
}
